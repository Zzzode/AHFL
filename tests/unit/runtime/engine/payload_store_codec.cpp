// ---- decode helpers (fixed key + generous caps unless overridden) -----------

constexpr std::uint64_t kBigCap = 1u << 20;

bool slot_admits(std::span<const std::uint8_t> b, std::uint64_t cap = kBigCap) {
    const auto id = test_key_id();
    return decode_slot(b, std::span<const std::uint8_t, 16>(id), test_key(), cap).has_value();
}
bool manifest_admits(std::span<const std::uint8_t> b, std::uint64_t cap = kBigCap) {
    const auto id = test_key_id();
    return decode_manifest(b, std::span<const std::uint8_t, 16>(id), test_key(), cap).has_value();
}
bool pointer_admits(std::span<const std::uint8_t> b) {
    const auto id = test_key_id();
    return decode_pointer(b, std::span<const std::uint8_t, 16>(id), test_key()).has_value();
}

PayloadStoreError slot_error(std::span<const std::uint8_t> b, std::uint64_t cap = kBigCap) {
    const auto id = test_key_id();
    auto r = decode_slot(b, std::span<const std::uint8_t, 16>(id), test_key(), cap);
    return r.has_value() ? PayloadStoreError::NotFound /*sentinel: means "admitted"*/ : r.error();
}
PayloadStoreError manifest_error(std::span<const std::uint8_t> b, std::uint64_t cap = kBigCap) {
    const auto id = test_key_id();
    auto r = decode_manifest(b, std::span<const std::uint8_t, 16>(id), test_key(), cap);
    return r.has_value() ? PayloadStoreError::NotFound : r.error();
}
PayloadStoreError pointer_error(std::span<const std::uint8_t> b) {
    const auto id = test_key_id();
    auto r = decode_pointer(b, std::span<const std::uint8_t, 16>(id), test_key());
    return r.has_value() ? PayloadStoreError::NotFound : r.error();
}

